# w-style module: help (user-scope) — the Help window (w-help) in the current theme.
# The documentation site keeps every colour, radius and font behind a custom
# property whose default is theme `w` (site/assets/style.css); this axis overrides
# those properties with the CURRENT theme in the Help profile's userContent.css,
# scoped to the site's own URL so nothing else that profile might load is touched.
# Every value carries !important: a user sheet loses to the author's :root rule
# without it. The logo is swapped through `content: url()` on the <img> — Gecko
# honours it on replaced elements, so the brand follows the theme too.
# NOT live — Firefox reads userContent.css at startup; reopen the Help window.
DESC="Help window: the documentation site in the current theme (not live)"

HELP_USERCONTENT_REL=".local/share/w/help/chrome/userContent.css"   # w-help's PROFILE

render_user() {
  local theme_dir logo scheme
  theme_dir="$(w_userscope_theme_dir)"
  load_conf "$theme_dir"
  load_font "$(resolve_theme_file "$theme_dir" font.conf)"
  load_geometry "$(resolve_theme_file "$theme_dir" geometry.conf)"
  logo="$(resolve_theme_file "$theme_dir" "$THEME_LOGO_SVG_REL")"
  scheme="dark"; [[ "${W_APPEARANCE:-dark}" == "light" ]] && scheme="light"
  echo "w-style: rendering Help window theme..."

  write_user_file "$HELP_USERCONTENT_REL" <<EOF
/* W Linux — generated by w-style (apply help). Do not edit; edit the active theme.
 * Variables: site/assets/style.css. Restart the Help window to apply. */
@-moz-document url-prefix("file:///usr/share/doc/w/html/") {
  :root {
    --w-bg: $W_APP_BG !important;
    --w-surface-dim: $W_SURFACE_DIM !important;
    --w-surface: $W_SURFACE !important;
    --w-surface-variant: $W_SURFACE_VARIANT !important;
    --w-text: $W_ON_SURFACE !important;
    --w-text-dim: $W_ON_SURFACE_VARIANT !important;
    --w-text-bright: $W_ON_SURFACE_BRIGHT !important;
    --w-text-faint: $W_ON_SURFACE_FAINT !important;
    --w-accent-ink: $W_ON_SURFACE_ACCENT !important;
    --w-primary: $W_PRIMARY !important;
    --w-primary-container: $W_PRIMARY_CONTAINER !important;
    --w-on-primary: $W_ON_PRIMARY !important;
    --w-vivid: $W_ACCENT_ALT !important;
    --w-green: $W_PALETTE_HUE_GREEN !important;
    --w-yellow: $W_PALETTE_HUE_YELLOW !important;
    --w-cyan: $W_PALETTE_HUE_CYAN !important;
    --w-radius: ${W_GEO_RADIUS}px !important;
    --w-radius-sm: ${W_GEO_RADIUS_SM}px !important;
    --w-font-ui: "$W_FONT_UI", system-ui, sans-serif !important;
    --w-font-mono: "$W_FONT_MONO", ui-monospace, monospace !important;
    color-scheme: $scheme !important;
  }
  .brand img { content: url("file://$logo") !important; }
}
EOF

  echo "w-style: Help window done (reopen it to apply)."
}
