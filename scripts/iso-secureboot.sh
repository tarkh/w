#!/usr/bin/env bash
# scripts/iso-secureboot.sh ISO — make a mkarchiso image boot under Secure Boot.
#
# No project key exists and nothing is signed here. The chain is closed by hashes,
# with the one link a user adds by hand once per image:
#   firmware (Microsoft 3rd-party UEFI CA) → Fedora shim (EFI/BOOT/BOOTX64.EFI)
#   → grubx64.efi = pristine Limine + .sbat + the BLAKE2B of limine.conf, trusted by
#     its authenticode SHA-256 in shim's MokList (MokManager → "Enroll hash from disk")
#   → limine.conf pins kernel and initramfs by BLAKE2B, and the cmdline with them
#   → the initramfs carries /codesign.crt of the build's one-off CMS pair
#     (mkarchiso -c), so cms_verify=y refuses a tampered airootfs.sfs.
# See package-limine.md §«Модель Secure Boot».
#
# Rewrites ISO in place: the EFI system partition (appended partition 2) is rebuilt
# from what mkarchiso put there — systemd-boot, its entries, the IA32 loader and the
# EFI shell out; shim, MokManager, Limine-for-shim and limine.conf in (label
# W_LINUX_EFI). The ISO 9660 copy of EFI/ and loader/ is brought to the same state,
# for a medium made by copying the image's files onto a FAT stick. The limine.conf
# entries are the ones mkarchiso rendered for systemd-boot (one source of truth:
# archiso/profile/efiboot/), memtest excepted — Limine has no use for it.
#
# Writes ISO.mok-sha256 (and /w/mok-sha256 on the medium): the authenticode hash a
# user's MokList ends up holding.
# Needs no root. Called by build-iso.sh; runnable on its own over any fresh
# mkarchiso image built with -c (iterate on the boot chain without a rebuild).
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_DIR="$(dirname "$SCRIPT_DIR")"
W_REPO_SRC="${W_REPO_SRC:-$PROJECT_DIR/archiso/w-repo}"
LIMINE_EFI=/usr/share/limine/BOOTX64.EFI

die()  { echo -e "\033[1;31mERROR:\033[0m $*" >&2; exit 1; }
info() { echo -e "\033[1;35m==>\033[0m $*"; }

ISO="${1:-}"
[[ -f "$ISO" ]] || die "usage: iso-secureboot.sh ISO"
for c in xorriso mcopy mkfs.fat objcopy objdump limine b2sum bsdtar python3; do
  command -v "$c" &>/dev/null || die "$c not found (limine, mtools, dosfstools, binutils, libisoburn, python-pefile)"
done
[[ -f "$LIMINE_EFI" ]] || die "no $LIMINE_EFI — pacman -S limine"
shopt -s nullglob
shim_pkg=("$W_REPO_SRC"/shim-signed-*.pkg.tar.*)
shopt -u nullglob
((${#shim_pkg[@]} == 1)) || die "expected one shim-signed package in $W_REPO_SRC"
# shellcheck source=rootfs/usr/lib/w/w-sbat-lib.sh
source "$PROJECT_DIR/rootfs/usr/lib/w/w-sbat-lib.sh"

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
esp="$work/esp"
mkdir -p "$esp"

# Without the CMS signature cms_verify=y drops every boot to a rescue shell.
xorriso -no_rc -indev "$ISO" -find /w/x86_64/airootfs.sfs.cms.sig 2>/dev/null | grep -q cms.sig \
  || die "$ISO has no airootfs.sfs.cms.sig — built without mkarchiso -c?"

# ── 1. The ESP mkarchiso made: appended partition 2 (MBR type 0xef, 512-byte blocks)
read -r start blocks < <(xorriso -no_rc -indev "$ISO" -report_system_area plain 2>/dev/null \
  | awk '$1=="MBR" && $2=="partition" && $6=="0xef" {print $7, $8; exit}')
[[ -n "${blocks:-}" ]] || die "no EFI system partition in $ISO"
dd if="$ISO" of="$work/old.img" bs=512 skip="$start" count="$blocks" status=none
mcopy -s -n -i "$work/old.img" '::*' "$esp/"
[[ -d "$esp/loader/entries" ]] || die "no systemd-boot entries on the ESP of $ISO — rebuilt already?"

# ── 2. limine.conf from the systemd-boot entries, in their sort-key order ─────────
timeout="$(awk '$1=="timeout" {print $2}' "$esp/loader/loader.conf")"
conf="$work/limine.conf"
printf '# Generated by scripts/iso-secureboot.sh — every file and cmdline pinned by hash.\ntimeout: %s\n' \
  "${timeout:-15}" > "$conf"
uuid=""
while IFS=$'\t' read -r _ f; do
  title="" linux="" initrd="" options=""
  while read -r k v; do
    case "$k" in
      title) title="$v" ;; linux) linux="$v" ;; initrd) initrd="$v" ;; options) options="$v" ;;
    esac
  done < "$f"
  [[ -n "$linux" ]] || continue  # memtest: an efi entry
  [[ -n "$initrd" && -n "$title" ]] || die "incomplete entry $(basename "$f")"
  [[ "$options" =~ archisosearchuuid=([^ ]+) ]] && uuid="${BASH_REMATCH[1]}"
  printf '\n/%s\n    protocol: linux\n    path: boot():%s#%s\n    module_path: boot():%s#%s\n    cmdline: %s cms_verify=y\n' \
    "$title" "$linux" "$(b2sum "$esp$linux" | cut -c1-128)" \
    "$initrd" "$(b2sum "$esp$initrd" | cut -c1-128)" "$options" >> "$conf"
done < <(for f in "$esp"/loader/entries/*.conf; do
           printf '%s\t%s\n' "$(awk '$1=="sort-key" {print $2}' "$f")" "$f"
         done | LC_ALL=C sort)
grep -q '^/' "$conf" || die "no linux entries among the systemd-boot entries"
[[ -n "$uuid" ]] || die "no archisosearchuuid in the entries"

# ── 3. The new ESP ────────────────────────────────────────────────────────────────
rm -rf "$esp/loader" "$esp/shellx64.efi" "$esp/EFI/BOOT"
mkdir -p "$esp/EFI/BOOT"
bsdtar -xf "${shim_pkg[0]}" -C "$work" usr/share/shim-signed/shimx64.efi usr/share/shim-signed/mmx64.efi
cp "$work/usr/share/shim-signed/shimx64.efi" "$esp/EFI/BOOT/BOOTX64.EFI"
cp "$work/usr/share/shim-signed/mmx64.efi"   "$esp/EFI/BOOT/mmx64.efi"
w_sbat_build "$LIMINE_EFI" "$esp/EFI/BOOT/grubx64.efi" "$(pacman -Q limine 2>/dev/null | awk '{print $2}')"
limine enroll-config "$esp/EFI/BOOT/grubx64.efi" "$(b2sum "$conf" | cut -c1-128)" >/dev/null
cp "$conf" "$esp/limine.conf"

# Sized as mkarchiso sizes its own: contents + 8 MiB, rounded up to a whole MiB.
kib="$(du -bcs "$esp" | awk 'END {print int(($1 / 1024 + 8192 + 1023) / 1024) * 1024}')"
mkfs.fat -C -F 32 -n W_LINUX_EFI "$work/efiboot.img" "$kib" >/dev/null
mcopy -s -i "$work/efiboot.img" "$esp"/* ::/

# The hash also travels on the medium (/w/mok-sha256, outside every hash it pins):
# the installer drops it from MokList once W's own key goes in (install.sh).
hash="$(python3 -I "$SCRIPT_DIR/pe-authenticode.py" "$esp/EFI/BOOT/grubx64.efi")"
printf '%s  EFI/BOOT/grubx64.efi\n' "$hash" > "$work/mok-sha256"

# ── 4. Repack: the boot setup replayed, the new ESP appended in place of the old ─
# The volume date is the archisosearchuuid the initramfs looks the medium up by;
# a rewrite would otherwise stamp a new one.
info "Repacking $(basename "$ISO") with the Secure Boot chain..."
xorriso -no_rc -report_about SORRY -indev "$ISO" -outdev "$ISO.w-new" \
  -joliet on -volume_date uuid "${uuid//-/}" \
  -boot_image any replay \
  -append_partition 2 0xef "$work/efiboot.img" \
  -boot_image any efi_path=--interval:appended_partition_2:all:: \
  -rm_r /loader /shellx64.efi /EFI/BOOT -- \
  -map "$esp/EFI/BOOT" /EFI/BOOT \
  -map "$conf" /limine.conf \
  -map "$work/mok-sha256" /w/mok-sha256 \
  || { rm -f "$ISO.w-new"; die "xorriso repack failed"; }
mv -f "$ISO.w-new" "$ISO"

cp "$work/mok-sha256" "$ISO.mok-sha256"
info "MokList hash (authenticode SHA-256 of EFI/BOOT/grubx64.efi): $hash"
