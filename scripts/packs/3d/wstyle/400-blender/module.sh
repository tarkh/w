# w-style module: blender (user-scope) — Blender interface theme.
#
# Ships INSIDE the 3d W-Pack (source of truth); `w-pack install 3d` drops this
# axis into the w-style modules.d drop-in root and renders it. Core w-style
# carries no reference to Blender → the axis exists iff the bundle is installed
# (packs.md "bundle self-containment", pack-3d.md).
#
# Blender is neither GTK nor Qt — it draws every pixel from its own theme (~570
# colours in preferences.themes[0]), and the theme lives in its binary
# userpref.blend, not in a file another program could write. So this axis does
# not render a Blender theme file: it renders a small JSON — a base (Blender's
# own Dark/Light preset, by W_APPEARANCE) plus W colour overrides keyed by RNA
# path ('*' as the first segment = every editor that has the rest). The W
# startup module of the pack (/usr/share/w/blender/scripts/startup/
# w_integration.py) composes the two into the user preset "W", makes it active
# and re-applies it whenever this file changes — LIVE in a running Blender, at
# the next start otherwise; a theme the user picked themselves is never
# overridden (ownership rule in that module). Everything not mapped below keeps
# Blender's own value, so a Blender release adding theme slots needs no change.
#
# Mapping principles — the same roles every W app uses: the surface ramp
# W_APP_BG (editor canvas) → SURFACE_DIM (headers, panels, sidebars) → SURFACE
# (popovers, menus) → SURFACE_VARIANT (raised buttons); inputs recess to
# W_APP_BG; selection is the W pair PRIMARY_CONTAINER + ON_PRIMARY_CONTAINER;
# W_PRIMARY marks "active" (focused editor outline, active object, playhead,
# cursor); text tones W_ON_SURFACE*; text-editor syntax from the shell roles.
# Viewport semantics Blender users read by colour (axis X/Y/Z, keyframe types,
# bone/collection colours, icon tints) are deliberately left alone.
# #rrggbb keeps the slot's own alpha (sidebars, selection overlays are
# translucent by design). No new theme.conf tokens. Band 400 = per-app GUI.
DESC="Blender interface theme"

BLENDER_THEME_REL=".config/w/blender-theme.json"

render_user() {
  local theme_dir; theme_dir="$(w_userscope_theme_dir)"
  load_conf "$theme_dir"
  echo "w-style: rendering blender theme..."

  local base=dark; [[ "$W_APPEARANCE" == light ]] && base=light

  # Button-like widgets share one shape: raised fill, accent selection.
  local w raised="" inputs="" menus=""
  for w in wcol_regular wcol_toggle wcol_radio wcol_menu wcol_tool wcol_toolbar_item; do
    raised+="
    \"user_interface.$w.inner\": \"$W_SURFACE_VARIANT\",
    \"user_interface.$w.inner_sel\": \"$W_PRIMARY_CONTAINER\",
    \"user_interface.$w.outline\": \"$W_SURFACE\",
    \"user_interface.$w.item\": \"$W_ON_SURFACE\",
    \"user_interface.$w.text\": \"$W_ON_SURFACE\",
    \"user_interface.$w.text_sel\": \"$W_ON_PRIMARY_CONTAINER\","
  done
  for w in wcol_text wcol_num wcol_numslider; do
    inputs+="
    \"user_interface.$w.inner\": \"$W_APP_BG\",
    \"user_interface.$w.inner_sel\": \"$W_SURFACE_VARIANT\",
    \"user_interface.$w.outline\": \"$W_SURFACE\",
    \"user_interface.$w.item\": \"$W_PRIMARY_CONTAINER\",
    \"user_interface.$w.text\": \"$W_ON_SURFACE\",
    \"user_interface.$w.text_sel\": \"$W_ON_SURFACE_BRIGHT\","
  done
  for w in wcol_menu_back wcol_pie_menu wcol_tooltip; do
    menus+="
    \"user_interface.$w.inner\": \"$W_SURFACE\",
    \"user_interface.$w.outline\": \"$W_SURFACE_VARIANT\",
    \"user_interface.$w.item\": \"$W_ON_SURFACE_VARIANT\",
    \"user_interface.$w.text\": \"$W_ON_SURFACE\",
    \"user_interface.$w.text_sel\": \"$W_ON_SURFACE_BRIGHT\","
  done

  write_user_file "$BLENDER_THEME_REL" <<EOF
{
  "_comment": "Generated by w-style (axis blender) — do not edit; edit the theme's theme.conf",
  "base": "$base",
  "colors": {
    "*.space.back": "$W_APP_BG",
    "*.space.header": "$W_SURFACE_DIM",
    "*.space.title": "$W_ON_SURFACE",
    "*.space.text": "$W_ON_SURFACE",
    "*.space.text_hi": "$W_ON_SURFACE_BRIGHT",
    "*.space.header_text": "$W_ON_SURFACE",
    "*.space.header_text_hi": "$W_ON_SURFACE_BRIGHT",
    "view_3d.space.gradients.high_gradient": "$W_SURFACE_DIM",
    "view_3d.space.gradients.gradient": "$W_APP_BG",
    "regions.sidebars.back": "$W_SURFACE_DIM",
    "regions.sidebars.tab_back": "$W_APP_BG",
    "regions.asset_shelf.back": "$W_SURFACE_DIM",
    "regions.asset_shelf.header_back": "$W_SURFACE_DIM",
    "regions.channels.back": "$W_SURFACE_DIM",
    "regions.scrubbing.back": "$W_SURFACE_DIM",
    "regions.scrubbing.time_marker_selected": "$W_PRIMARY",

    "user_interface.editor_border": "$W_BG",
    "user_interface.editor_outline": "$W_SURFACE_DIM",
    "user_interface.editor_outline_active": "$W_PRIMARY",
    "user_interface.panel_header": "$W_SURFACE_DIM",
    "user_interface.panel_back": "$W_SURFACE_DIM",
    "user_interface.panel_sub_back": "$W_APP_BG",
    "user_interface.panel_outline": "$W_SURFACE",
    "user_interface.panel_title": "$W_ON_SURFACE",
    "user_interface.panel_text": "$W_ON_SURFACE",
    "user_interface.panel_active": "$W_PRIMARY",
    "user_interface.widget_text_cursor": "$W_PRIMARY",$raised$inputs$menus
    "user_interface.wcol_option.inner": "$W_SURFACE_VARIANT",
    "user_interface.wcol_option.inner_sel": "$W_PRIMARY",
    "user_interface.wcol_option.item": "$W_ON_PRIMARY",
    "user_interface.wcol_option.text": "$W_ON_SURFACE",
    "user_interface.wcol_option.text_sel": "$W_ON_SURFACE",
    "user_interface.wcol_pulldown.inner_sel": "$W_SURFACE_VARIANT",
    "user_interface.wcol_pulldown.text": "$W_ON_SURFACE",
    "user_interface.wcol_pulldown.text_sel": "$W_ON_SURFACE_BRIGHT",
    "user_interface.wcol_menu_item.inner_sel": "$W_PRIMARY_CONTAINER",
    "user_interface.wcol_menu_item.item": "$W_ON_SURFACE_VARIANT",
    "user_interface.wcol_menu_item.text": "$W_ON_SURFACE",
    "user_interface.wcol_menu_item.text_sel": "$W_ON_PRIMARY_CONTAINER",
    "user_interface.wcol_list_item.inner_sel": "$W_PRIMARY_CONTAINER",
    "user_interface.wcol_list_item.item": "$W_PRIMARY_CONTAINER",
    "user_interface.wcol_list_item.text": "$W_ON_SURFACE",
    "user_interface.wcol_list_item.text_sel": "$W_ON_PRIMARY_CONTAINER",
    "user_interface.wcol_tab.inner": "$W_SURFACE_DIM",
    "user_interface.wcol_tab.inner_sel": "$W_SURFACE_VARIANT",
    "user_interface.wcol_tab.outline": "$W_APP_BG",
    "user_interface.wcol_tab.text": "$W_ON_SURFACE_VARIANT",
    "user_interface.wcol_tab.text_sel": "$W_ON_SURFACE_BRIGHT",
    "user_interface.wcol_box.inner": "$W_SURFACE_DIM",
    "user_interface.wcol_box.outline": "$W_SURFACE",
    "user_interface.wcol_scroll.item": "$W_SURFACE_VARIANT",
    "user_interface.wcol_progress.inner": "$W_SURFACE_DIM",
    "user_interface.wcol_progress.item": "$W_PRIMARY",
    "user_interface.wcol_state.error": "$W_ERROR",

    "view_3d.object_active": "$W_PRIMARY",
    "view_3d.object_selected": "$W_PRIMARY_SOFT",
    "view_3d.vertex_select": "$W_PRIMARY",
    "view_3d.edge_select": "$W_PRIMARY",
    "view_3d.edge_mode_select": "$W_PRIMARY",
    "view_3d.face_select": "$W_PRIMARY",
    "view_3d.face_mode_select": "$W_PRIMARY",
    "node_editor.node_active": "$W_PRIMARY",
    "node_editor.node_selected": "$W_PRIMARY_SOFT",
    "node_editor.wire_select": "$W_PRIMARY",
    "outliner.active": "$W_PRIMARY_CONTAINER",
    "outliner.selected_highlight": "$W_PRIMARY_CONTAINER",
    "outliner.active_object": "$W_ON_SURFACE_BRIGHT",
    "outliner.selected_object": "$W_ON_SURFACE_ACCENT",
    "common.anim.playhead": "$W_PRIMARY",

    "text_editor.cursor": "$W_PRIMARY",
    "text_editor.selected_text": "$W_PRIMARY_CONTAINER",
    "text_editor.line_numbers": "$W_ON_SURFACE_VARIANT",
    "text_editor.line_numbers_background": "$W_SURFACE_DIM",
    "text_editor.syntax_builtin": "$W_SHELL_FUNCTION",
    "text_editor.syntax_reserved": "$W_SHELL_KEYWORD",
    "text_editor.syntax_string": "$W_SHELL_STRING",
    "text_editor.syntax_numbers": "$W_SHELL_NUMBER",
    "text_editor.syntax_comment": "$W_SHELL_COMMENT",
    "text_editor.syntax_symbols": "$W_SHELL_OPERATOR"
  }
}
