# Binary twin of write_user_file: same scope rule (skel as root, $HOME as user),
# same IN-PLACE semantics (truncate + write keeps the inode tdesktop's
# QFileSystemWatcher is armed on) — write_user_file itself goes through a bash
# string and would drop the NUL bytes of a ZIP. $1 = relative target, $2 = file.
_tg_write_binary() {
  local rel="$1" src="$2" target
  if [[ $EUID -eq 0 ]]; then target="/etc/skel/$rel"; else target="$HOME/$rel"; fi
  mkdir -p "$(dirname "$target")"
  cat "$src" >"$target" && chmod 644 "$target"
}

