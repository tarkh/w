# w-style module: telegram (user-scope) — Telegram Desktop palette.
#
# Ships INSIDE the telegram W-Pack (source of truth); `w-pack install telegram`
# drops this axis into the w-style modules.d drop-in root, `w-pack remove` takes
# it back. Core w-style carries no reference to Telegram → the axis exists iff
# the bundle is installed (packs.md "bundle self-containment", pack-telegram.md).
#
# Telegram Desktop (tdesktop) is Qt but paints every pixel from its OWN palette
# (~590 named colours, `colors.palette` in lib_ui) — the `qt` axis does not reach
# it. Its theme format: a plain-text palette (`key: #rrggbb[aa];` or
# `key: otherKey;`) — or a ZIP holding that text as `colors.tdesktop-theme` plus
# a chat wallpaper (`background.{jpg,png}` stretched, `tiled.{jpg,png}` tiled;
# window_theme.cpp loadBackground). Keys left unset are derived from the ones
# set (the default palette is mostly aliases), unknown keys are ignored.
#
# This axis writes the ZIP form: the palette plus a one-colour `tiled.png`, so
# the chat wallpaper is a flat W surface instead of tdesktop's stock pattern
# (its bundled wallpapers are all light or busy; there is no "plain colour"
# choice for a local theme, and a theme's own background is the sanctioned
# channel). A theme that carries a background applies it on every Apply —
# including the live reload — so the wallpaper is the theme's, not the user's:
# a wallpaper picked in Chat settings lasts until the next theme render. That
# is the intended ownership (W owns Telegram's look while the pack is on).
# Target: `w.tdesktop-theme` in the app's own data dir next to `tdata/` (skel
# as root → every new account has it).
#
# Which theme tdesktop USES lives in its encrypted `tdata`, with no external
# "apply" channel. Two ways this file gets there: an account whose Telegram
# never ran gets a seeded tdata from the bundle's setup-user.sh (tdata-seed.py
# — settingss + a theme record pointing here, so the first launch is already
# W); an account with a running history applies it ONCE by hand, after signing
# in (Chat settings exist only with an account): Settings → Chat settings →
# Chat background → "Choose from file" → this file → Keep changes. Either way,
# from then on everything is automatic (verified in the tdesktop source, `dev`
# branch, 2026-09-12):
#   * LIVE — tdesktop puts a QFileSystemWatcher on the applied file and calls
#     Apply()+KeepApplied() on every change, silently: `w-theme set` recolours a
#     running Telegram. Needs the in-place write of write_user_file (same inode).
#   * At START — readThemeUsingKey() re-reads the file and, if its content
#     differs from the cached copy, drops the cache: a theme switched while the
#     app was closed shows up at the next launch.
#
# Mapping principles (matugen's telegram template served as the key list; the
# roles are W's, not Material's): the surface ramp W_APP_BG → SURFACE_DIM →
# SURFACE → SURFACE_VARIANT for window/hover/ripple/raised; text tones
# W_ON_SURFACE* (names and bold = BRIGHT); the accent split fill/ink as
# everywhere in W — W_PRIMARY fills buttons and badges, W_ON_SURFACE_ACCENT is
# the accent drawn as text (links, service lines, active labels); outgoing
# bubbles are the W selection idiom, W_PRIMARY_CONTAINER + ON_PRIMARY_CONTAINER
# (the active-tab / launcher-row / terminal-selection pair), not the raw accent;
# the eight peer-name colours and the file-thumbnail hues are the ANSI wheel;
# W_DANGER* for errors and destructive; translucent composites as #rrggbbaa.
# No new theme.conf tokens. Band 400 = per-app GUI config.
